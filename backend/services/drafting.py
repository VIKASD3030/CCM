def _generate_ref_no() -> str:
    """Random reference number in the fixed SYSTRA format, e.g. SMCIPL/CPMS/GoTS/25/007."""
    yy = datetime.now().strftime("%y")
    seq = random.randint(1, 999)
    return f"SMCIPL/CPMS/GoTS/{yy}/{seq:03d}"


def _format_long_date(d: date) -> str:
    """Format a date like '4th December 2025' to match the reference letter."""
    day = d.day
    if 11 <= day % 100 <= 13:
        suffix = "th"
    else:
        suffix = {1: "st", 2: "nd", 3: "rd"}.get(day % 10, "th")
    return f"{day}{suffix} {d.strftime('%B %Y')}"


def _clean_lines(value, *, fallback: str | None = None) -> list[str]:
    """Normalise a model-supplied string or list into a list of non-empty lines."""
    if isinstance(value, str):
        parts = [ln.strip() for ln in re.split(r"[\r\n]+", value)]
    elif isinstance(value, (list, tuple)):
        parts = [str(ln).strip() for ln in value]
    else:
        parts = []
    parts = [p for p in parts if p]
    if parts:
        return parts
    return [fallback] if fallback else []


def _normalise_paragraphs(value) -> list[str]:
    if isinstance(value, str):
        paras = [p.strip() for p in re.split(r"\n\s*\n", value) if p.strip()]
    elif isinstance(value, (list, tuple)):
        paras = [str(p).strip() for p in value if str(p).strip()]
    else:
        paras = []
    return paras or [
        "With reference to the subject cited above, we acknowledge receipt of your "
        "letter and confirm that the matter is receiving our attention."
    ]


def _normalise_enclosures(value) -> list[str]:
    if isinstance(value, str):
        return [e.strip(" .") for e in re.split(r"\n|;", value) if e.strip(" .")]
    if isinstance(value, (list, tuple)):
        return [str(e).strip(" .") for e in value if str(e).strip(" .")]
    return []


# Honorifics that indicate a female addressee → "Respected Madam,"
_FEMALE_TITLES = ("ms.", "ms ", "mrs.", "mrs ", "miss ", "madam", "smt.", "smt ")


def _derive_salutation(attention: str | None, recipient_name: str | None) -> str:
    """Pick 'Respected Sir,' / 'Respected Madam,' from available recipient info.

    Deterministic — not asked of the LLM.
    """
    probe = " ".join(x for x in (attention, recipient_name) if x).lower()
    if any(t in probe for t in _FEMALE_TITLES):
        return "Respected Madam,"
    return "Respected Sir,"


def build_letter_data(fields: dict, *, ref_no: str, letter_date: str) -> dict:
    """Turn the model's JSON body fields into the validated, structured LetterData
    consumed by the deterministic SYSTRA template (plain-text + rich HTML)."""
    rec_in = fields.get("recipient")
    if not isinstance(rec_in, dict):
        # Legacy shape: a flat list of recipient lines.
        legacy = _clean_lines(fields.get("recipient_lines"))
        rec_in = {
            "attention": None,
            "name": legacy[0] if legacy else None,
            "organization": legacy[1] if len(legacy) > 1 else None,
            "address_lines": legacy[2:],
        }

    attention = (rec_in.get("attention") or "").strip() or None
    name = (rec_in.get("name") or "").strip() or None
    organization = (rec_in.get("organization") or "").strip() or None
    address_lines = _clean_lines(rec_in.get("address_lines"))

    def _clean(val, fallback):
        return (str(val).strip() if val not in (None, "") else "") or fallback

    return {
        "reference_number": ref_no,
        "date": letter_date,
        "recipient": {
            "attention": attention,
            "name": name,
            "organization": organization,
            "address_lines": address_lines,
        },
        "subject": _clean(fields.get("subject"), "Response to your recent correspondence"),
        "project": (str(fields.get("project")).strip() or None) if fields.get("project") else None,
        "reference": (str(fields.get("ref")).strip() or None) if fields.get("ref") else None,
        "salutation": _derive_salutation(attention, name),
        "opening_line": SYSTRA_OPENING_LINE,
        "body": _normalise_paragraphs(fields.get("body_paragraphs") or fields.get("body")),
        "closing_lines": list(SYSTRA_CLOSING_LINES),
        "signatory": _generate_signatory(),
        "enclosure": _normalise_enclosures(fields.get("enclosures")),
        "branding": dict(SYSTRA_BRANDING),
    }


def render_systra_letter(letter_data: dict) -> str:
    """Assemble the plain-text letter from structured LetterData + fixed template."""
    rec = letter_data.get("recipient") or {}
    recipient_lines: list[str] = []
    if rec.get("attention"):
        recipient_lines.append(f"Kind Attn: {rec['attention']}")
        recipient_lines.append("")
    if rec.get("name"):
        recipient_lines.append(rec["name"])
    if rec.get("organization"):
        recipient_lines.append(rec["organization"])
    recipient_lines.extend(rec.get("address_lines") or [])
    if not recipient_lines:
        recipient_lines = ["The Authorised Signatory"]

    meta = [f"Subject: {letter_data['subject']}"]
    if letter_data.get("project"):
        meta.append(f"Project: {letter_data['project']}")
    if letter_data.get("reference"):
        meta.append(f"Ref: {letter_data['reference']}")

    encl_items = letter_data.get("enclosure") or []
    if not encl_items:
        enclosures = "Nil"
    elif len(encl_items) == 1:
        enclosures = f"1. {encl_items[0]}"
    else:
        enclosures = "\n" + "\n".join(f"{i}. {e}" for i, e in enumerate(encl_items, 1))

    branding = letter_data.get("branding") or SYSTRA_BRANDING
    sig = letter_data.get("signatory") or _generate_signatory()
    desig2 = sig.get("designation_line_2")

    return SYSTRA_LETTER_TEMPLATE.format(
        company_name=branding["company_name"],
        offices="\n".join(branding["offices"]),
        contact_information=branding["contact_information"],
        ref_no=letter_data["reference_number"],
        letter_date=letter_data["date"],
        recipient_block="\n".join(recipient_lines),
        meta_block="\n".join(meta),
        salutation=letter_data.get("salutation", "Respected Sir,"),
        opening_line=letter_data.get("opening_line", SYSTRA_OPENING_LINE),
        body="\n\n".join(letter_data.get("body") or []),
        closing_lines="\n".join(letter_data.get("closing_lines") or SYSTRA_CLOSING_LINES),
        signatory_name=sig["name"],
        signatory_designation_1=sig["designation_line_1"],
        signatory_designation_2=f"\n{desig2}" if desig2 else "",
        signatory_for=sig["for_company"],
        enclosures=enclosures,
    )

