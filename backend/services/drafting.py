async def generate_draft(
    db: AsyncSession,
    letter_id: str,
    additional_instructions: str = "",
    user_id: uuid.UUID = None,
) -> DraftResponse:
    """
    Generate an AI draft response for a letter using RAG.
    1. Fetch the letter
    2. Search knowledge base for relevant context (scoped to project)
    3. Build prompt with context
    4. Call AI to generate draft
    5. Store and return
    """
    letter = await db.get(InboundLetter, str(letter_id))
    if not letter:
        raise ValueError(f"Letter {letter_id} not found")

    if not letter.category:
        # Upload no longer blocks on classification (it now happens in the
        # background so the upload response is instant). If it hasn't finished
        # by the time a draft is requested, classify here instead — one LLM
        # call, ~1-2s — so category-specific drafting instructions still apply.
        from backend.services.letter_intake import classify_letter
        classification = await classify_letter(letter.raw_text)
        letter.category = classification.get("category")
        letter.urgency = classification.get("urgency")
        letter.intent = classification.get("intent")
        letter.confidence_score = classification.get("confidence_score")
        letter.key_entities = classification.get("key_entities")
        if letter.status == "new":
            letter.status = "classified"
        await db.flush()
        logger.info("draft.classified_inline", letter_id=str(letter_id))

    relevant_chunks = await search_similar_chunks(
        db, letter.raw_text, top_k=5, project_id=str(letter.project_id) if letter.project_id else None
    )

    context_parts = []
    context_doc_ids = []
    for i, chunk in enumerate(relevant_chunks, 1):
        source = chunk.get("metadata", {}).get("filename", "Unknown")
        context_parts.append(
            f"[Document {i}: {source} | Relevance: {chunk['similarity']}]\n{chunk['chunk_text']}"
        )
        context_doc_ids.append({
            "document_id": chunk["document_id"],
            "chunk_id": chunk["chunk_id"],
            "similarity": chunk["similarity"],
            "source": source,
        })

    context_text = "\n\n".join(context_parts) if context_parts else "No relevant context found in the knowledge base."

    category_instructions = CATEGORY_INSTRUCTIONS.get(
        letter.category or "general_inquiry",
        CATEGORY_INSTRUCTIONS["general_inquiry"],
    )

    ref_no = _generate_ref_no()
    letter_date = _format_long_date(date.today())

    prompt = DRAFTING_PROMPT.format(
        category=letter.category or "general_inquiry",
        urgency=letter.urgency or "medium",
        letter_text=letter.raw_text,
        intent=letter.intent or "Not classified",
        context=context_text,
        category_instructions=category_instructions,
        additional_instructions=f"\nADDITIONAL INSTRUCTIONS:\n{additional_instructions}" if additional_instructions else "",
    )

    try:
        raw = await openai_client.call_openai_async(
            prompt=f"{DRAFTING_SYSTEM_PROMPT}\n\n{prompt}",
            model=draft_model,
            temperature=0.6,
            max_output_tokens=3000,
            response_format={"type": "json_object"},
        )
    except Exception as e:
        logger.error("draft.generation_failed", letter_id=str(letter_id), error=str(e))
        raise

    try:
        fields = json.loads(raw)
        if not isinstance(fields, dict):
            raise ValueError("model did not return a JSON object")
    except (json.JSONDecodeError, ValueError) as e:
        logger.warning("draft.json_parse_failed", letter_id=str(letter_id), error=str(e))
        fields = {"body_paragraphs": [raw.strip()]}

    # Deterministic assembly: LLM supplies only body fields; branding, ref no.,
    # date, salutation, signatory and layout all come from fixed config.
    letter_data = build_letter_data(fields, ref_no=ref_no, letter_date=letter_date)
    draft_text = render_systra_letter(letter_data)

    version_count = await db.execute(
        select(func.count())
        .select_from(DraftResponse)
        .where(DraftResponse.letter_id == str(letter_id))
    )
    version = (version_count.scalar() or 0) + 1

    draft_id = uuid.uuid4()
    draft = DraftResponse(
        id=draft_id,
        letter_id=str(letter_id),
        draft_text=draft_text,
        letter_data=letter_data,
        version=version,
        status="pending_review",
        context_documents=context_doc_ids,
        feedback=additional_instructions if additional_instructions else None,
        edited_by=user_id,
    )
    db.add(draft)

    letter.status = "drafted"

    audit = AuditEntry(
        entity_type="draft",
        entity_id=str(draft_id),
        action="draft_generated",
        user_id=user_id,
        details={
            "letter_id": str(letter_id),
            "version": version,
            "context_chunks_used": len(relevant_chunks),
            "model": settings.generation_model,
            "ref_no": ref_no,
        },
    )
    db.add(audit)
    await db.flush()

    logger.info("draft.generated", version=version, letter_id=str(letter_id), user_id=str(user_id) if user_id else None)

    # Dispatch webhook (fire-and-forget)
    await dispatch_event("draft.generated", {
        "draft_id": str(draft.id),
        "letter_id": str(letter_id),
        "version": version,
        "generated_by": str(user_id) if user_id else None,
    })

    return draft


async def regenerate_draft(
    db: AsyncSession,
    draft_id: str,
    feedback: str,
    user_id: uuid.UUID = None,
) -> DraftResponse:
    """Re-generate a draft with additional feedback/instructions."""
    old_draft = await db.get(DraftResponse, str(draft_id))
    if not old_draft:
        raise ValueError(f"Draft {draft_id} not found")

    old_draft.status = "revised"
    old_draft.feedback = feedback

    new_draft = await generate_draft(
        db, old_draft.letter_id, additional_instructions=feedback, user_id=user_id
    )

    return new_draft


async def update_draft_text(
    db: AsyncSession,
    draft_id: str,
    new_text: str,
    user_id: uuid.UUID = None,
) -> dict | None:
    """Manually edit the draft text."""
    draft = await db.get(DraftResponse, str(draft_id))
    if not draft:
        return None

    draft.draft_text = new_text
    draft.edited_by = user_id

    audit = AuditEntry(
        entity_type="draft",
        entity_id=str(draft_id),
        action="manually_edited",
        user_id=user_id,
        details={"letter_id": str(draft.letter_id)},
    )
    db.add(audit)
    await db.flush()

    return draft.to_dict()


async def get_drafts_for_letter(
    db: AsyncSession,
    letter_id: str,
    user_id: uuid.UUID = None,
    user_role: str = None,
    skip: int = 0,
    limit: int = 50,
) -> tuple[list[dict], int]:
    """Get draft versions for a letter with row-level security and pagination.
    Returns (drafts, total_count).
    """
    letter = await db.get(InboundLetter, str(letter_id))
    if not letter:
        return [], 0

    if user_role != "admin" and user_id is not None:
        if letter.created_by != user_id:
            return [], 0

    count_result = await db.execute(
        select(func.count())
        .select_from(DraftResponse)
        .where(DraftResponse.letter_id == str(letter_id))
    )
    total = count_result.scalar() or 0

    stmt = (
        select(DraftResponse)
        .where(DraftResponse.letter_id == str(letter_id))
        .order_by(DraftResponse.version.desc())
        .offset(skip)
        .limit(limit)
    )
    result = await db.execute(stmt)
    drafts = result.scalars().all()
    return [d.to_dict() for d in drafts], total


async def get_draft_by_id(
    db: AsyncSession,
    draft_id: str,
    user_id: uuid.UUID = None,
    user_role: str = None,
) -> dict | None:
    """Get a single draft by ID with row-level security."""
    draft = await db.get(DraftResponse, str(draft_id))
    if not draft:
        return None

    letter = await db.get(InboundLetter, str(draft.letter_id))
    if not letter:
        return None

    if user_role != "admin" and user_id is not None:
        if letter.created_by != user_id:
            return None

    return draft.to_dict()
